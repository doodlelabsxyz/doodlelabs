// Pulls every file out of the ImageKit "Creatives" and "videos" folders and
// writes their paths to lib/imagekit-assets.generated.ts, which
// lib/portfolio-data.ts reads from. Re-run after uploading new files.
//
// Usage: node --env-file=.env.local scripts/sync-imagekit.mjs

import ImageKit from "@imagekit/nodejs";
import { writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const IMAGE_EXT = /\.(png|jpe?g|webp|avif|gif|svg)$/i;
const VIDEO_EXT = /\.(mp4|mov|webm|m4v)$/i;

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const client = new ImageKit();

async function listFolder(folderPath) {
  const files = await client.assets.list({
    path: folderPath,
    type: "file",
    limit: 1000,
  });
  return files.filter((f) => f.filePath).map((f) => f.filePath);
}

const [creatives, videos] = await Promise.all([listFolder("/Creatives"), listFolder("/videos")]);

const images = creatives.filter((p) => IMAGE_EXT.test(p)).sort();
const clips = videos.filter((p) => VIDEO_EXT.test(p)).sort();

const out = `// Auto-generated by scripts/sync-imagekit.mjs — do not edit by hand.
// Re-run \`npm run sync:imagekit\` after uploading new files to ImageKit.

export const creativeImages: string[] = ${JSON.stringify(images, null, 2)};

export const videoClips: string[] = ${JSON.stringify(clips, null, 2)};
`;

await writeFile(path.join(__dirname, "..", "lib", "imagekit-assets.generated.ts"), out);

console.log(`Synced ${images.length} image(s) from /Creatives and ${clips.length} video(s) from /videos.`);
console.log("Written to lib/imagekit-assets.generated.ts");
